import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, readdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { authoredFingerprint, withArtifactLocks } from './isolated-build-integrity.mjs';

/** Fixture writing only. Hold the same locks as prepare/build/start for the
 * entire action. Callbacks must observe stopped processes and the exact owned
 * idle-state policy; neither callback may acquire these locks again. */
export async function withEvidencePreparationFence({ repositoryRoot, appRoot, expectedSource, verifyStopped, verifyIdle }, action, publish) {
  assert.match(expectedSource ?? '', /^[a-f0-9]{64}$/);
  assert.equal(typeof verifyStopped, 'function'); assert.equal(typeof verifyIdle, 'function');
  const repository = resolve(repositoryRoot), root = resolve(appRoot);
  assert.match(root.slice(resolve(repository, '.data/autonomy-isolation').length), /^[\\/]application-[a-z0-9]+$/);
  assert.ok(root.startsWith(resolve(repository, '.data/autonomy-isolation')));
  return withArtifactLocks(root, ['dependencies', 'web', 'eve'], async () => {
    const manifestPath = resolve(root, 'source-manifest.json'), original = await readFile(manifestPath);
    const source = JSON.parse(original);
    assert.equal(source.sourceSha256, expectedSource);
    assert.ok(Array.isArray(source.files) && source.files.length > 0 && new Set(source.files).size === source.files.length);
    // Exact files generated by prepareIsolatedApp, absent from the checkout.
    // They remain covered by the full frozen hash, never by an unchecked read.
    const generated = ['.cssnanorc.json', 'tests/helpers/observe-http.mjs', 'tests/helpers/isolation-module-fence.mjs'];
    const authored = source.files.filter(file => !generated.includes(file));
    const frozenAuthoredSha256 = await authoredFingerprint(resolve(root, 'web'), authored);
    const assertExclusive = async () => {
      assert.ok(original.equals(await readFile(manifestPath)), 'Frozen source manifest changed during fixture preparation');
      assert.equal(await authoredFingerprint(resolve(root, 'web'), source.files), expectedSource, 'Frozen web source changed');
      assert.equal(await authoredFingerprint(repository, authored), frozenAuthoredSha256, 'Preparation code differs from the frozen source');
      // isolatedApp imports all schema files by directory listing. Reject an
      // added un-frozen module even if no existing importer changed its bytes.
      const schemaFiles = await readdir(resolve(repository, 'server/db/schema'), { withFileTypes: true }).catch(error => { if (error.code !== 'ENOENT') throw error; return []; });
      assert.ok(schemaFiles.every(file => !file.isSymbolicLink()));
      assert.deepEqual(schemaFiles.filter(file => file.isFile() && file.name.endsWith('.ts')).map(file => `server/db/schema/${file.name}`).sort(),
        authored.filter(file => /^server\/db\/schema\/[^/]+\.ts$/.test(file)).sort(), 'Preparation schema inventory differs from the frozen source');
      await verifyStopped();
    };
    await assertExclusive();
    const before = await verifyIdle();
    await assertExclusive();
    const identity = { version: 1, sourceSha256: expectedSource,
      manifestSha256: createHash('sha256').update(original).digest('hex'),
      workingAndFrozenAuthoredMatch: true, authoredSha256: frozenAuthoredSha256, locks: ['dependencies', 'eve', 'web'], idleBefore: before };
    const result = await action({ assertExclusive, identity });
    await assertExclusive();
    const after = await verifyIdle();
    await assertExclusive();
    const receipt = { ...identity, idleAfter: after, completedAt: new Date().toISOString() };
    // Publish usable manifests only after the checks, still under the locks.
    // Abrupt death during action cannot leave a usable acceptance manifest.
    return { result: publish ? await publish(result, receipt) : result, receipt };
  });
}
